#!/usr/bin/env bash
# Generate deploy/rr-nav2-bridge.container (rootless Podman Quadlet unit) from the same
# hardened flags as scripts/run.sh, then validate it with Podman's quadlet generator.
# It does NOT install anything. To install (user service), copy it yourself:
#   mkdir -p ~/.config/containers/systemd
#   cp deploy/rr-nav2-bridge.container ~/.config/containers/systemd/
#   systemctl --user daemon-reload && systemctl --user start rr-nav2-bridge
set -euo pipefail
source "$(dirname "$0")/config.sh"
OUT_DIR="$PROJECT_ROOT/deploy"; mkdir -p "$OUT_DIR"
OUT="$OUT_DIR/rr-nav2-bridge.container"

args=()
for a in "${HARDENED_RUN_FLAGS[@]}" "${RR_NET_FLAGS[@]}"; do args+=("$a"); done
{
    echo "# Generated by scripts/quadlet.sh from scripts/config.sh - do not edit by hand."
    echo "# Same hardening and limits as scripts/run.sh. RR port: $RR_BIND_ADDR:$RR_PORT."
    echo "[Unit]"
    echo "Description=Robot Raconteur Nav2 bridge (ROS 2 Jazzy, algorithm only)"
    echo "After=network-online.target"
    echo
    echo "[Container]"
    echo "Image=$IMAGE"
    echo "ContainerName=$RUN_NAME"
    # One flag (or flag + value) per PodmanArgs line keeps the unit readable.
    i=0
    while (( i < ${#args[@]} )); do
        a="${args[$i]}"
        if [[ "$a" != *=* && $((i + 1)) -lt ${#args[@]} && "${args[$((i + 1))]}" != -* ]]; then
            echo "PodmanArgs=$a ${args[$((i + 1))]}"; i=$((i + 2))
        else
            echo "PodmanArgs=$a"; i=$((i + 1))
        fi
    done
    echo
    echo "[Service]"
    echo "Restart=on-failure"
    echo "RestartSec=5"
    echo "TimeoutStopSec=30"
    echo
    echo "[Install]"
    echo "WantedBy=default.target"
} > "$OUT"
echo "wrote $OUT"

# Validate: run the generator in dry-run mode on just this file.
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
cp "$OUT" "$tmp/"
if QUADLET_UNIT_DIRS="$tmp" /usr/libexec/podman/quadlet -user -dryrun > "$tmp/out.txt" 2>&1; then
    grep -q "^ExecStart=" "$tmp/out.txt" && echo "quadlet dry-run OK" || { cat "$tmp/out.txt"; exit 1; }
else
    cat "$tmp/out.txt"; exit 1
fi
